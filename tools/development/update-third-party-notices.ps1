[CmdletBinding()]
param([switch]$Check)
Set-StrictMode -Version Latest
$ErrorActionPreference = 'Stop'
$root = [IO.Path]::GetFullPath((Join-Path $PSScriptRoot '../..'))
$utf8 = [Text.UTF8Encoding]::new($false)
Push-Location $root
try {
    $toolchain = [IO.File]::ReadAllText((Join-Path $root 'rust-toolchain.toml'))
    $sdk = [IO.File]::ReadAllText((Join-Path $root 'global.json')) | ConvertFrom-Json
    if ($toolchain -notmatch '(?m)^channel\s*=\s*"1\.98\.0"\s*$' -or $sdk.sdk.version -ne '10.0.400') {
        throw 'Refresh the retained Rust/.NET host notices and their version references for the new toolchain pins.'
    }
    foreach ($required in @('licenses/rust-1.98.0/COPYRIGHT-library.html', 'licenses/dotnet-apphost-10.0.11/LICENSE.TXT', 'licenses/dotnet-apphost-10.0.11/THIRD-PARTY-NOTICES.TXT')) {
        if (-not [IO.File]::Exists((Join-Path $root $required))) { throw "Missing retained license material: $required" }
    }
    # Offline, locked metadata avoids changing dependency versions during attribution.
    $metadataText = & cargo metadata --locked --offline --format-version 1
    if ($LASTEXITCODE -ne 0) { throw 'Cannot read locked Cargo metadata. Populate the dependency cache first.' }
    $metadata = ($metadataText -join "`n") | ConvertFrom-Json
    $selections = @{
        'MIT' = 'MIT'; 'MIT OR Apache-2.0' = 'MIT'; 'Apache-2.0 OR MIT' = 'MIT'
        'MIT/Apache-2.0' = 'MIT'; 'Apache-2.0/MIT' = 'MIT'; 'Unlicense OR MIT' = 'MIT'
        'BSD-2-Clause OR Apache-2.0 OR MIT' = 'MIT'
        'Apache-2.0 WITH LLVM-exception OR Apache-2.0 OR MIT' = 'MIT'
        'MIT OR Apache-2.0 OR LGPL-2.1-or-later' = 'MIT'
        '(MIT OR Apache-2.0) AND Unicode-3.0' = 'MIT AND Unicode-3.0'
        'Unicode-3.0' = 'Unicode-3.0'; 'Apache-2.0' = 'Apache-2.0'; 'Zlib' = 'Zlib'
        'CDLA-Permissive-2.0' = 'CDLA-Permissive-2.0'
        '(Apache-2.0 OR MIT) AND BSD-3-Clause' = 'MIT AND BSD-3-Clause'
        '0BSD OR MIT OR Apache-2.0' = 'MIT'; 'Apache-2.0 / MIT' = 'MIT'
        'Apache-2.0 OR BSL-1.0' = 'Apache-2.0'
        'BSD-2-Clause' = 'BSD-2-Clause'; 'BSD-3-Clause' = 'BSD-3-Clause'
        'BSD-3-Clause OR Apache-2.0' = 'BSD-3-Clause'
        'CC0-1.0 OR Apache-2.0 OR Apache-2.0 WITH LLVM-exception' = 'Apache-2.0'
        'CC0-1.0 OR MIT-0 OR Apache-2.0' = 'Apache-2.0'
        'MIT OR Apache-2.0 OR BSD-1-Clause' = 'MIT'
        'MIT OR Apache-2.0 OR WTFPL' = 'MIT'
        'MIT OR Apache-2.0 OR Zlib' = 'MIT'; 'MIT OR Zlib OR Apache-2.0' = 'MIT'
        'Zlib OR Apache-2.0 OR MIT' = 'MIT'
    }
    $text = [Text.StringBuilder]::new()
    $null = $text.AppendLine(@'
md2hwp third-party notices
=========================

The original md2hwp code is AGPL-3.0-only; see LICENSE.
Third-party components retain their own copyright and licensing terms.
The entries below cover exact versions in Cargo.lock on all target platforms,
including build tools and components not linked into the Windows executables.
Where alternatives exist, the selected permissive branch is stated explicitly.
Other supplied license texts and supplemental notices are retained for completeness;
their inclusion does not require selecting every alternative license.
Supplemental Unicode tables and adapted-code notices remain applicable.

Rust 1.98.0 standard-library attribution and associated license texts are retained
verbatim in licenses/rust-1.98.0/. That upstream inventory is broader than the
components used by this application. Main Rust library license selection: MIT;
exceptions, Unicode data, and target-specific supplemental notices remain intact.
Source: https://github.com/rust-lang/rust/tree/1.98.0

The .NET single-file host (Microsoft.NETCore.App.Host.win-x64 10.0.11) license and
third-party notices are retained verbatim in licenses/dotnet-apphost-10.0.11/.
The exact NuGet package declares MIT. Its singlefilehost.exe was checked against
the host from the pinned SDK. The Microsoft Windows SDK product license is not
substituted for that package's own license. The full .NET runtime is not bundled.
Source: https://github.com/dotnet/dotnet/tree/e2f47b0110ed922f21a1522da67279133ce28f32
Package: https://www.nuget.org/packages/Microsoft.NETCore.App.Host.win-x64/10.0.11

Pandoc, Hancom HWP, the Hancom security module and font files are not bundled.
Pandoc setup preserves the separately downloaded upstream COPYRIGHT and source
link. Users' manuscripts and external templates retain their respective rights.

Generated by tools/development/update-third-party-notices.ps1; do not edit entries
by hand. Review new license expressions and notices when dependencies change.
'@)
    $vendorManifest = [IO.Path]::GetFullPath((Join-Path $root 'dependencies/vendor/svg2pdf/Cargo.toml'))
    $packages = @($metadata.packages | Where-Object {
        $null -ne $_.source -or [IO.Path]::GetFullPath($_.manifest_path) -eq $vendorManifest
    } | Sort-Object name, version)
    # These historical crate archives omit the license files. Revisions come
    # from each published archive's .cargo_vcs_info.json.
    $zuneSupplements = @{
        'zune-core-0.4.12' = 'f8fbb123d5ed04441e8324a555bfcda0cb1bd28f'
        'zune-jpeg-0.4.21' = 'fa2c767a01d7d9373911d0bf63e0588553d67e0e'
    }
    foreach ($package in $packages) {
        $expression = [string]$package.license
        if (-not $selections.ContainsKey($expression)) { throw "Review new license expression for $($package.name) $($package.version): $expression" }
        $selectedLicense = $selections[$expression]
        $packageKey = "$($package.name)-$($package.version)"
        $directory = [IO.Path]::GetDirectoryName($package.manifest_path)
        $source = [string]$package.source
        $searchOption = if ($source.StartsWith('git+https://github.com/edwardkim/rhwp?')) { [IO.SearchOption]::TopDirectoryOnly } else { [IO.SearchOption]::AllDirectories }
        $files = @([IO.Directory]::EnumerateFiles($directory, '*', $searchOption) |
            Where-Object { [IO.Path]::GetFileName($_) -match '^(?i:licen[sc]e|copying|copyright|notice|authors)([.\-_]|$)' } |
            Sort-Object)
        $sourceArchive = "https://crates.io/api/v1/crates/$($package.name)/$($package.version)/download"
        if ($source.StartsWith('git+https://github.com/edwardkim/rhwp?')) {
            if ($source -notmatch '#([0-9a-f]{40})$') { throw "Unpinned rhwp source: $source" }
            $revision = $Matches[1]
            $sourceArchive = "https://github.com/edwardkim/rhwp/archive/$revision.tar.gz"
            # Child crates share the root license rather than duplicating it.
            if ($files.Count -eq 0) {
                $sharedLicense = [IO.Path]::GetFullPath((Join-Path $directory '../../LICENSE'))
                if (-not [IO.File]::Exists($sharedLicense)) { throw "Missing rhwp shared license: $sharedLicense" }
                $files += $sharedLicense
            }
        } elseif ($source.StartsWith('git+')) {
            throw "Review source attribution for $source"
        } elseif ([IO.Path]::GetFullPath($package.manifest_path) -eq $vendorManifest) {
            $sourceArchive = 'https://github.com/edwardkim/rhwp/tree/1a76570e833917d15817415a53c09ad61ab3203f/vendor/svg2pdf'
        }
        if ($package.name -eq 'jsonschema' -and $package.version -eq '0.18.3') {
            $files += Join-Path $root 'licenses/supplemental/jsonschema-0.18.3-LICENSE.txt'
        }
        if ($zuneSupplements.ContainsKey($packageKey)) {
            # The exact historical commits provide a complete Zlib grant;
            # their MIT text is only linked, so select the declared Zlib branch.
            $selectedLicense = 'Zlib'
            $files += Join-Path $root "licenses/supplemental/$packageKey-LICENSE.md"
            $files += Join-Path $root "licenses/supplemental/$packageKey-LICENSE-ZLIB.txt"
        }
        if ($files.Count -eq 0) { throw "Missing license evidence for $($package.name) $($package.version)." }
        $null = $text.AppendLine("`n================================================================================")
        $null = $text.AppendLine("$($package.name) $($package.version)")
        $null = $text.AppendLine("Declared license: $expression")
        $null = $text.AppendLine("Selected license: $selectedLicense")
        $null = $text.AppendLine("Upstream: $($package.repository)")
        $null = $text.AppendLine("Exact source: $sourceArchive")
        if ($package.name -eq 'jsonschema' -and $package.version -eq '0.18.3') {
            $null = $text.AppendLine('Supplemental LICENSE: https://raw.githubusercontent.com/Stranger6667/jsonschema/11ebbaaececc1830f093dca229a28c0a5ebdf877/LICENSE')
        }
        if ($zuneSupplements.ContainsKey($packageKey)) {
            $supplementBase = "https://raw.githubusercontent.com/etemesi254/zune-image/$($zuneSupplements[$packageKey])"
            $null = $text.AppendLine("Supplemental LICENSE: $supplementBase/LICENSE.md")
            $null = $text.AppendLine("Supplemental Zlib license: $supplementBase/LICENSE-ZLIB")
        }
        foreach ($file in $files) {
            $relative = [IO.Path]::GetRelativePath($directory, $file).Replace('\', '/')
            if (-not $file.StartsWith($directory + [IO.Path]::DirectorySeparatorChar, [StringComparison]::OrdinalIgnoreCase)) {
                $relative = if ($source.StartsWith('git+https://github.com/edwardkim/rhwp?')) { '../../LICENSE (shared rhwp license)' } else { [IO.Path]::GetRelativePath($root, $file).Replace('\', '/') }
            }
            $null = $text.AppendLine("`n--- $relative ---`n")
            $null = $text.AppendLine([IO.File]::ReadAllText($file, $utf8).TrimEnd())
        }
        if ($package.name -eq 'rhwp' -and $source.StartsWith('git+https://github.com/edwardkim/rhwp?')) {
            # rhwp includes a BSD-licensed algorithm port beyond its MIT package license.
            # Retain that upstream attribution without importing its unrelated web/font inventory.
            $upstreamNotices = [IO.File]::ReadAllText((Join-Path $directory 'THIRD_PARTY_LICENSES.md'), $utf8)
            $portedAlgorithms = [regex]::Match($upstreamNotices, '(?ms)^## 직접 포팅한 알고리즘\r?\n.*?(?=^## )')
            if (-not $portedAlgorithms.Success) { throw 'Review changed rhwp supplemental algorithm notices.' }
            $null = $text.AppendLine("`n--- THIRD_PARTY_LICENSES.md: ported algorithms ---`n")
            $null = $text.AppendLine($portedAlgorithms.Value.TrimEnd())
        }
    }
    $content = $text.ToString().Replace("`r`n", "`n")
    $destination = Join-Path $root 'THIRD-PARTY-NOTICES.txt'
    if ($Check) {
        if (-not [IO.File]::Exists($destination) -or [IO.File]::ReadAllText($destination, $utf8).Replace("`r`n", "`n") -cne $content) {
            throw 'THIRD-PARTY-NOTICES.txt is stale. Run this script without -Check and review the changes.'
        }
    } else {
        [IO.File]::WriteAllText($destination, $content, $utf8)
    }
    Write-Output "Third-party notices verified for $($packages.Count) locked packages."
} finally { Pop-Location }
