"""Prepare native captures using the actual SCRIPT -> TeX -> SCRIPT pipeline."""
import argparse
import hashlib
import json
from pathlib import Path
import subprocess

ROOT = Path(__file__).resolve().parents[2]

def convert(executable, direction, value):
    result = subprocess.run([str(executable), direction], input=value, encoding='utf-8',
                            capture_output=True, check=False)
    if result.returncode:
        raise RuntimeError(f'{direction}: {result.stderr.strip()}')
    return result.stdout.rstrip('\r\n')

def prepare(executable, output):
    groups = [('gallery','supported-equations.json',46),('toolbar','toolbar-equations.json',76)]
    for name, filename, count in groups:
        source = ROOT/'crates/md2hwp-math/tests/fixtures'/filename
        raw = source.read_bytes()
        cases = json.loads(raw.decode('utf-8'))['cases']
        if len(cases) != count:
            raise ValueError(f'Unexpected {name} case count')
        compiled = []
        for item in cases:
            original = item['hancom_script']
            tex = convert(executable,'hml-to-tex',original)
            reconstructed = convert(executable,'tex-to-hml',tex)
            compiled.append({'case_id': item.get('case_id',item.get('id')),
                             'name':item['name'],'category':item.get('category','수식 왕복'),
                             'original_script':original,'tex':tex,'script':reconstructed})
        data = {'count':count,'source':{'path':str(source.resolve()),
                'sha256':hashlib.sha256(raw).hexdigest(),'use':'Original fixture; scripts below are generated by both converter directions.'},
                'pipeline':['hml_to_tex','tex_to_hml'],'cases':compiled}
        destination=output/'inputs'/f'{name}.json'
        destination.parent.mkdir(parents=True,exist_ok=True)
        destination.write_text(json.dumps(data,ensure_ascii=False,indent=2)+'\n',encoding='utf-8')
        print(name,len(compiled),'roundtrips prepared',flush=True)

if __name__=='__main__':
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--converter',type=Path,default=ROOT/'target/debug/md2hwp-math.exe')
    parser.add_argument('--output',type=Path,default=ROOT/'artifacts/math-roundtrip')
    args=parser.parse_args()
    prepare(args.converter.resolve(),args.output.resolve())
